-- QRスタンプラリー用データベース定義（Supabase）
-- 何度実行しても同じ状態になるように書いています。既存のデータは削除しません。
-- 旧版から更新するときは、景品発送先（氏名・住所など）を survey_responses から
-- prize_shipping に自動で移し替えます（移し替えを確認できない場合は、何も変更せずに中止します）。
-- SupabaseのSQL Editorに全体を貼り付けて Run してください。
begin;

-- ============================================================
-- 1. 基本テーブル
-- ============================================================
create table if not exists public.scan_events (
  id bigint generated by default as identity primary key,
  participant_id text not null,
  stamp_code text not null check (stamp_code in ('river','bridge','fish','island','water','goal')),
  scanned_at timestamptz not null default now(),
  user_agent text
);

create table if not exists public.stamp_claims (
  id bigint generated by default as identity primary key,
  participant_id text not null,
  stamp_code text not null check (stamp_code in ('river','bridge','fish','island','water','goal')),
  sequence integer not null check (sequence between 1 and 6),
  first_scanned_at timestamptz not null default now(),
  unique (participant_id, stamp_code),
  unique (participant_id, sequence)
);

-- アンケートの回答。氏名・住所などの個人情報は、別テーブル prize_shipping に分けて保存する。
create table if not exists public.survey_responses (
  id bigint generated by default as identity primary key,
  participant_id text not null,
  submitted_at timestamptz not null default now(),
  satisfaction integer check (satisfaction between 1 and 5),
  memorable_spot text,
  comment text,
  prize_requested boolean not null default false,
  workshop_participation text,
  unique (participant_id)
);

-- 旧版の列名 completion_participant_id を participant_id にそろえる
do $$
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'survey_responses' and column_name = 'completion_participant_id'
  ) then
    alter table public.survey_responses rename column completion_participant_id to participant_id;
  end if;
end $$;

alter table public.survey_responses alter column prize_requested set default false;

-- 初回取得（true）と再スキャン（false）を区別する
alter table public.scan_events add column if not exists is_first_claim boolean;

-- 列追加前の行は、参加者×スタンプごとの最初の読み取りを初回取得とみなして埋める
update public.scan_events e
set is_first_claim = (e.id = f.first_id)
from (
  select participant_id, stamp_code, min(id) as first_id
  from public.scan_events
  group by participant_id, stamp_code
) f
where e.is_first_claim is null
  and e.participant_id = f.participant_id
  and e.stamp_code = f.stamp_code;

create index if not exists scan_events_scanned_at_idx on public.scan_events (scanned_at desc, id desc);
create index if not exists scan_events_participant_idx on public.scan_events (participant_id);

-- アンケート：暗渠ワークショップ（ちよだ家プロジェクト）への参加有無
alter table public.survey_responses add column if not exists workshop_participation text;
alter table public.survey_responses drop constraint if exists survey_workshop_participation_check;
alter table public.survey_responses add constraint survey_workshop_participation_check check (
  workshop_participation is null
  or workshop_participation in ('attended', 'not_attended', 'unsure')
);

-- ============================================================
-- 2. 景品発送先（個人情報）：アンケート回答とは別のテーブルに保存する
-- ============================================================
create table if not exists public.prize_shipping (
  participant_id text primary key references public.survey_responses (participant_id) on delete cascade,
  created_at timestamptz not null default now(),
  recipient_name text not null,
  postal_code text not null,
  address text not null,
  phone text not null,
  consent boolean not null default false,
  privacy_version text
);

-- 旧版（survey_responses に発送先の列があった版）からの移し替え。
-- 全件の移し替えを確認できたときだけ、旧い列を削除する。確認できなければ全体を中止する。
do $$
declare
  v_unmigrated integer;
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'survey_responses' and column_name = 'recipient_name'
  ) then
    alter table public.survey_responses drop constraint if exists survey_prize_fields_check;
    alter table public.survey_responses add column if not exists privacy_version text;

    insert into public.prize_shipping
      (participant_id, created_at, recipient_name, postal_code, address, phone, consent, privacy_version)
    select r.participant_id, r.submitted_at, r.recipient_name, r.postal_code, r.address, r.phone,
           coalesce(r.consent, false), r.privacy_version
    from public.survey_responses r
    where r.recipient_name is not null and r.postal_code is not null
      and r.address is not null and r.phone is not null
    on conflict (participant_id) do nothing;

    select count(*) into v_unmigrated
    from public.survey_responses r
    where (r.recipient_name is not null or r.postal_code is not null
           or r.address is not null or r.phone is not null)
      and not exists (select 1 from public.prize_shipping s where s.participant_id = r.participant_id);

    if v_unmigrated > 0 then
      raise exception '発送先の移し替えを確認できない行が % 件あります。何も変更せずに中止します。', v_unmigrated;
    end if;

    alter table public.survey_responses
      drop column recipient_name, drop column postal_code, drop column address,
      drop column phone, drop column consent, drop column privacy_version;
  end if;
end $$;

-- 入力値の範囲（旧版で保存済みの行は検査せず、新しく保存・更新する行だけを検査する）
alter table public.prize_shipping drop constraint if exists prize_shipping_values_check;
alter table public.prize_shipping add constraint prize_shipping_values_check check (
  length(recipient_name) between 1 and 100
  and length(postal_code) between 3 and 20
  and length(address) between 1 and 300
  and length(phone) between 5 and 30
  and consent
) not valid;

