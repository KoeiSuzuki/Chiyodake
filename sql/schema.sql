-- 同期トークンを発行する（SQL Editorから実行。表示は1回だけで、以前のトークンは無効になる）
--   select private.issue_sheets_token();
create or replace function private.issue_sheets_token()
returns text
language plpgsql
security definer
set search_path = private, public
as $$
declare
  v_token text := replace(gen_random_uuid()::text || gen_random_uuid()::text, '-', '');
begin
  delete from private.sheets_sync_tokens where true;
  insert into private.sheets_sync_tokens (token_hash)
  values (encode(sha256(convert_to(v_token, 'UTF8')), 'hex'));
  return v_token;
end;
$$;
revoke all on function private.issue_sheets_token() from public, anon, authenticated;

create or replace function private.assert_sheets_token(p_token text)
returns void
language plpgsql
security definer
set search_path = private, public
as $$
begin
  if p_token is null or not exists (
    select 1 from private.sheets_sync_tokens
    where token_hash = encode(sha256(convert_to(p_token, 'UTF8')), 'hex')
  ) then
    raise exception 'invalid sync token' using errcode = '42501';
  end if;
end;
$$;
revoke all on function private.assert_sheets_token(text) from public, anon, authenticated;

-- データが変わったかを調べるための「指紋」。対象のテーブルの全行から計算するので、
-- 追加・変更・削除のどれでも値が変わる（行の数だけでなく、中身が書き換わった場合も検出する）。
-- 先頭の 'export-v2' は、出力の形式を変えたときに値を変えて、全体を書き直させるための印。
create or replace function private.sheets_fingerprint()
returns text
language sql
stable
set search_path = public, private
as $$
  select md5(concat_ws('|', 'export-v2',
    (select count(*) || ':' || coalesce(sum(hashtextextended(t::text, 0)), 0) from public.scan_events t),
    (select count(*) || ':' || coalesce(sum(hashtextextended(t::text, 0)), 0) from public.stamp_claims t),
    (select count(*) || ':' || coalesce(sum(hashtextextended(t::text, 0)), 0) from public.survey_responses t),
    (select count(*) || ':' || coalesce(sum(hashtextextended(t::text, 0)), 0) from public.prize_shipping t),
    (select count(*) || ':' || coalesce(sum(hashtextextended(t::text, 0)), 0) from public.excluded_participants t)
  ));
$$;
revoke all on function private.sheets_fingerprint() from public, anon, authenticated;

-- 管理画面とスプレッドシートの「概要」に共通する集計。除外した参加者は含めない。
create or replace function private.stats_json()
returns jsonb
language sql
stable
set search_path = public, private
as $$
  with pa as (select * from public.v_admin_participants),
  p as (select * from pa where not is_excluded),
  sc as (select * from public.v_admin_scans where not is_excluded),
  cl as (
    select c.* from public.stamp_claims c
    where not exists (select 1 from public.excluded_participants x where x.participant_id = c.participant_id)
  ),
  sv as (
    select r.* from public.survey_responses r
    where not exists (select 1 from public.excluded_participants x where x.participant_id = r.participant_id)
  )
  select jsonb_build_object(
    'summary', jsonb_build_object(
      'participants', (select count(*) from p),
      'completers', (select count(*) from p where completed),
      'total_scans', (select count(*) from sc),
      'rescans', (select count(*) from sc where is_first_claim is false),
      'surveys', (select count(*) from sv),
      'prize_requests', (select count(*) from sv where prize_requested),
      'avg_satisfaction', (select round(avg(satisfaction)::numeric, 2) from sv),
      'excluded_participants', (select count(*) from pa where is_excluded)
    ),
    -- 獲得数別の人数（どこで離脱しているか）
    'funnel', (
      select jsonb_agg(jsonb_build_object(
        'stamps', k,
        'exact', (select count(*) from p where p.stamps = k),
        'at_least', (select count(*) from p where p.stamps >= k),
        'ratio', case when (select count(*) from p) > 0
                      then round((select count(*) from p where p.stamps >= k)::numeric / (select count(*) from p), 4) end
      ) order by k)
      from generate_series(1, 6) k
    ),
    -- 日別（日本時間の日付ごと。新しい順）
    'daily', coalesce((
      select jsonb_agg(jsonb_build_object(
        'date', to_char(d, 'YYYY/MM/DD'),
        'new_participants', (select count(*) from p where (p.first_scan_at at time zone 'Asia/Tokyo')::date = d),
        'scans', (select count(*) from sc where (sc.scanned_at at time zone 'Asia/Tokyo')::date = d),
        'completers', (select count(*) from p where p.completed_at is not null
                         and (p.completed_at at time zone 'Asia/Tokyo')::date = d),
        'surveys', (select count(*) from sv where (sv.submitted_at at time zone 'Asia/Tokyo')::date = d)
      ) order by d desc)
      from (
        select (first_scan_at at time zone 'Asia/Tokyo')::date as d from p
        union select (scanned_at at time zone 'Asia/Tokyo')::date from sc
        union select (submitted_at at time zone 'Asia/Tokyo')::date from sv
      ) days
    ), '[]'::jsonb),
    -- ワークショップ参加有無別
    'workshop', (
      select jsonb_agg(jsonb_build_object(
        'label', g.label,
        'responses', (select count(*) from sv where sv.workshop_participation is not distinct from g.code),
        'avg_satisfaction', (select round(avg(sv.satisfaction)::numeric, 2) from sv
                             where sv.workshop_participation is not distinct from g.code),
        'prize_requests', (select count(*) from sv
                           where sv.workshop_participation is not distinct from g.code and sv.prize_requested)
      ) order by g.ord)
      from (values ('attended'::text, '参加した', 1), ('not_attended', '参加していない', 2),
                   ('unsure', 'わからない／覚えていない', 3), (null, '未回答（旧回答など）', 4)) as g(code, label, ord)
    ),
    -- 満足度の分布
    'satisfaction', (
      select jsonb_agg(jsonb_build_object('score', s, 'count', (select count(*) from sv where sv.satisfaction = s))
                       order by s desc)
      from generate_series(1, 5) s
    ),
    -- スポット別
    'spots', (
      select jsonb_agg(jsonb_build_object(
        'stamp_code', g.code,
        'stamp_name', g.name,
        'total_scans', (select count(*) from sc where sc.stamp_code = g.code),
        'unique_participants', (select count(distinct sc.participant_id) from sc where sc.stamp_code = g.code),
        'rescans', (select count(*) from sc where sc.stamp_code = g.code and sc.is_first_claim is false),
        'claimed_participants', (select count(*) from cl where cl.stamp_code = g.code),
        'acquisition_rate', case when (select count(*) from p) > 0
                                 then round((select count(*) from cl where cl.stamp_code = g.code)::numeric
                                            / (select count(*) from p), 4) end
      ) order by g.ord)
      from (values ('river', '川の入口', 1), ('bridge', '橋', 2), ('fish', '魚', 3),
                   ('island', '島', 4), ('water', '水辺', 5), ('goal', 'ゴール', 6)) as g(code, name, ord)
    )
  );
$$;
revoke all on function private.stats_json() from public, anon, authenticated;

