create or replace function public.stamp_name(p_code text)
returns text
language sql
immutable
set search_path = ''
as $$
  select case p_code
    when 'river' then '川の入口'
    when 'bridge' then '橋'
    when 'fish' then '魚'
    when 'island' then '島'
    when 'water' then '水辺'
    when 'goal' then 'ゴール'
  end;
$$;

create or replace function public.workshop_label(p_code text)
returns text
language sql
immutable
set search_path = ''
as $$
  select case p_code
    when 'attended' then '参加した'
    when 'not_attended' then '参加していない'
    when 'unsure' then 'わからない／覚えていない'
  end;
$$;

-- ブラウザ情報（user agent）から端末の種類を判定する。iPhoneのUAには "Mac OS X" も含まれるため、iPhoneを先に判定する。
create or replace function public.device_type(p_user_agent text)
returns text
language sql
stable
set search_path = ''
as $$
  select case
    when p_user_agent is null or btrim(p_user_agent) = '' then '不明'
    when p_user_agent ilike '%ipad%' then 'iPad'
    when p_user_agent ilike '%iphone%' or p_user_agent ilike '%ipod%' then 'iPhone'
    when p_user_agent ilike '%android%' and p_user_agent ilike '%mobile%' then 'Android'
    when p_user_agent ilike '%android%' then 'Androidタブレット'
    when p_user_agent ilike '%windows%' then 'Windows PC'
    when p_user_agent ilike '%macintosh%' then 'Mac'
    when p_user_agent ilike '%cros%' then 'Chromebook'
    when p_user_agent ilike '%linux%' then 'Linux PC'
    else 'その他'
  end;
$$;

-- ============================================================
-- 5. 管理画面用のビュー（security_invoker：閲覧者本人の権限で動くので、上のRLS＝管理者のみが効く）
-- ============================================================
-- 読み取り履歴（1回の読み取り＝1行）
create or replace view public.v_admin_scans with (security_invoker = true) as
select e.id,
       e.scanned_at,
       e.participant_id,
       e.stamp_code,
       public.stamp_name(e.stamp_code) as stamp_name,
       e.is_first_claim,
       case when e.is_first_claim then '初回取得' when e.is_first_claim is false then '再スキャン' end as scan_type,
       public.device_type(e.user_agent) as device,
       coalesce(e.user_agent like '% [resend]', false) as is_resend,
       e.user_agent,
       exists (select 1 from public.excluded_participants x where x.participant_id = e.participant_id) as is_excluded
from public.scan_events e;

-- 参加者ごとの状況（1人＝1行）
create or replace view public.v_admin_participants with (security_invoker = true) as
with ev as (
  select participant_id,
         count(*) as total_scans,
         count(*) filter (where is_first_claim is false) as rescans,
         min(scanned_at) as first_scan_at,
         max(scanned_at) as last_scan_at,
         (array_agg(user_agent order by scanned_at, id))[1] as first_user_agent
  from public.scan_events
  group by participant_id
), cl as (
  select participant_id,
         count(*) as stamps,
         max(first_scanned_at) as last_claim_at,
         max(first_scanned_at) filter (where stamp_code = 'river') as river_at,
         max(first_scanned_at) filter (where stamp_code = 'bridge') as bridge_at,
         max(first_scanned_at) filter (where stamp_code = 'fish') as fish_at,
         max(first_scanned_at) filter (where stamp_code = 'island') as island_at,
         max(first_scanned_at) filter (where stamp_code = 'water') as water_at,
         max(first_scanned_at) filter (where stamp_code = 'goal') as goal_at,
         string_agg(public.stamp_name(stamp_code), ' → ' order by sequence) as route,
         jsonb_agg(jsonb_build_object('stamp_code', stamp_code, 'sequence', sequence, 'at', first_scanned_at)
                   order by sequence) as claims
  from public.stamp_claims
  group by participant_id
)
select ev.participant_id,
       coalesce(cl.stamps, 0)::integer as stamps,
       coalesce(cl.stamps, 0) = 6 as completed,
       case when cl.stamps = 6 then cl.last_claim_at end as completed_at,
       cl.river_at, cl.bridge_at, cl.fish_at, cl.island_at, cl.water_at, cl.goal_at,
       cl.route,
       cl.claims,
       ev.first_scan_at,
       ev.last_scan_at,
       ev.total_scans,
       ev.rescans,
       public.device_type(ev.first_user_agent) as device,
       exists (select 1 from public.survey_responses r where r.participant_id = ev.participant_id) as survey_submitted,
       (select r.workshop_participation from public.survey_responses r where r.participant_id = ev.participant_id) as workshop_participation,
       exists (select 1 from public.excluded_participants x where x.participant_id = ev.participant_id) as is_excluded
from ev
left join cl using (participant_id);

-- 旧版の管理画面が使っているビュー。除外した参加者を含めないように更新する。
create or replace view public.v_dashboard_summary with (security_invoker = true) as
select
  (select count(*) from public.v_admin_participants where not is_excluded) as participants,
  (select count(*) from public.v_admin_participants where not is_excluded and completed) as completers,
  (select count(*) from public.v_admin_scans where not is_excluded) as total_scans;

create or replace view public.v_spot_stats with (security_invoker = true) as
select stamp_code, count(*) as total_scans,
       count(distinct participant_id) as unique_participants
from public.v_admin_scans
where not is_excluded
group by stamp_code order by stamp_code;

create or replace view public.v_participant_routes with (security_invoker = true) as
select c.participant_id, c.stamp_code, c.sequence, c.first_scanned_at,
       exists (select 1 from public.excluded_participants x where x.participant_id = c.participant_id) as is_excluded
from public.stamp_claims c
order by c.participant_id, c.sequence;

