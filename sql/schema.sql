-- 参加者を集計から除外する／除外を解除する。戻り値は、実際に変更があったか。
create or replace function public.admin_set_excluded(
  p_participant_id text,
  p_excluded boolean,
  p_reason text default null
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id text := btrim(coalesce(p_participant_id, ''));
begin
  if not public.is_admin() then
    raise exception 'admin only' using errcode = '42501';
  end if;
  if length(v_id) not between 4 and 64 then
    raise exception 'invalid participant id';
  end if;

  if coalesce(p_excluded, false) then
    insert into public.excluded_participants (participant_id, reason)
    values (v_id, left(nullif(btrim(coalesce(p_reason, '')), ''), 200))
    on conflict (participant_id) do nothing;
  else
    delete from public.excluded_participants where participant_id = v_id;
  end if;
  return found;
end;
$$;

-- 指定した日時より前に最初の読み取りがあった参加者を、まとめて除外する（本番開始前の動作確認データ用）。
-- 戻り値は、新しく除外した人数。
create or replace function public.admin_exclude_before(
  p_before timestamptz,
  p_reason text default 'テスト（本番開始前）'
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_count integer;
begin
  if not public.is_admin() then
    raise exception 'admin only' using errcode = '42501';
  end if;
  if p_before is null then
    raise exception 'p_before is required';
  end if;

  with added as (
    insert into public.excluded_participants (participant_id, reason)
    select participant_id, left(nullif(btrim(coalesce(p_reason, '')), ''), 200)
    from public.scan_events
    group by participant_id
    having min(scanned_at) < p_before
    on conflict (participant_id) do nothing
    returning 1
  )
  select count(*) into v_count from added;
  return v_count;
end;
$$;

-- 除外をすべて解除する。戻り値は、解除した人数。
create or replace function public.admin_clear_excluded()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_count integer;
begin
  if not public.is_admin() then
    raise exception 'admin only' using errcode = '42501';
  end if;
  with removed as (
    delete from public.excluded_participants where true returning 1
  )
  select count(*) into v_count from removed;
  return v_count;
end;
$$;

