create table if not exists public.stamp_events (
  id bigint generated by default as identity primary key,
  participant_id text not null,
  stamp_code text not null,
  sequence integer not null,
  scanned_at timestamptz not null default now(),
  user_agent text,
  created_at timestamptz not null default now(),
  unique(participant_id, stamp_code)
);

alter table public.stamp_events enable row level security;

-- 匿名参加者はINSERTのみ可能。
-- 読み取りはクライアントから許可しません。
drop policy if exists "allow anonymous insert" on public.stamp_events;
create policy "allow anonymous insert"
on public.stamp_events
for insert
to anon
with check (
  length(participant_id) between 4 and 64
  and stamp_code in ('river','bridge','fish','island','water','goal')
  and sequence between 1 and 6
);

